
i=1
sum=0

echo "=============================="
echo "  1 ~ 100 짝수 합산"
echo "=============================="
printf "  짝수: "

while [ $i -le 100 ]; do
    # 짝수 판별: i % 2 == 0
    if [ $((i % 2)) -eq 0 ]; then
        sum=$((sum + i))
        printf "%d " "$i"
    fi
    i=$((i + 1))
done

echo ""
echo "=============================="
echo "  짝수의 합계 : $sum"
echo "=============================="